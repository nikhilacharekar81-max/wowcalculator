export function getStateSalesTaxConfig(stateCode: string, transactionDate: string = '2026-01-01'): StateSalesTaxConfig {
  if (!stateCode || typeof stateCode !== 'string') {
    throw new Error('A valid state code is required.');
  }
  const code = stateCode.trim().toUpperCase();
  const cfg = SALES_TAX_CONFIG_2026[code];
  if (!cfg) {
    throw new Error(`State code ${code} not supported.`);
  }
  const parsedDate = new Date(transactionDate);
  if (isNaN(parsedDate.getTime())) {
    throw new Error(`Invalid transaction date format: ${transactionDate}.`);
  }
  const transactionYear = parsedDate.getFullYear();
  if (transactionYear !== 2026) {
    throw new Error(`Unsupported transaction date year: ${transactionYear}. WowCalc Sales Tax engine exclusively supports Tax Year 2026.`);
  }
  if (cfg.evidence?.effectiveFrom && parsedDate < new Date(cfg.evidence.effectiveFrom)) {
    throw new Error(`Transaction date ${transactionDate} is before the effective date ${cfg.evidence.effectiveFrom} of the rule ${cfg.evidence.ruleId}.`);
  }
  if (cfg.evidence?.effectiveTo && parsedDate > new Date(cfg.evidence.effectiveTo)) {
    throw new Error(`Transaction date ${transactionDate} is after the expiration date ${cfg.evidence.effectiveTo} of the rule ${cfg.evidence.ruleId}.`);
  }
  return JSON.parse(JSON.stringify(cfg));
}

